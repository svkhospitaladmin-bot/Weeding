let currentLanguage = 'mr';
const translatedElements = Array.from(document.querySelectorAll('[data-i18n]')).map(element => ({
  element, key: element.dataset.i18n, marathi: element.innerHTML
}));
const translatedAttributes = ['aria-label', 'alt'].flatMap(attribute =>
  Array.from(document.querySelectorAll(`[data-i18n-${attribute}]`)).map(element => ({
    element, attribute, key: element.getAttribute(`data-i18n-${attribute}`), marathi: element.getAttribute(attribute)
  }))
);
const calendarLinks = Array.from(document.querySelectorAll('a[href="wedding.ics"]'));

const t = key => runtimeCopy[currentLanguage][key] || '';
const refreshMenuLabel = () => {
  const button = document.querySelector('.menu-toggle');
  button.setAttribute('aria-label', t(button.getAttribute('aria-expanded') === 'true' ? 'menuClose' : 'menuOpen'));
};

function setStatus(selector, key = '', suffix = '') {
  const element = document.querySelector(selector);
  if (!key) {
    delete element.dataset.statusKey;
    delete element.dataset.statusSuffix;
    element.textContent = '';
    return;
  }
  element.dataset.statusKey = key;
  element.dataset.statusSuffix = suffix;
  element.textContent = t(key) + suffix;
}

function setLanguage(language, userAction = false) {
  if (language !== 'mr' && language !== 'en') return;
  const headerBottom = document.querySelector('.language-bar').getBoundingClientRect().bottom +
    (getComputedStyle(document.querySelector('.mobile-header')).display === 'none' ? 0 : 55);
  const anchor = userAction ? Array.from(document.querySelectorAll('main > section, main > footer'))
    .find(section => section.getBoundingClientRect().bottom > headerBottom) : null;
  const anchorTop = anchor?.getBoundingClientRect().top;
  currentLanguage = language;
  document.documentElement.lang = language;
  translatedElements.forEach(({ element, key, marathi }) => {
    element.innerHTML = language === 'en' ? englishCopy[key] : marathi;
  });
  translatedAttributes.forEach(({ element, attribute, key, marathi }) => {
    element.setAttribute(attribute, language === 'en' ? englishCopy[key] : marathi);
  });
  document.title = t('shareTitle');
  document.querySelector('meta[name="description"]').content = t('description');
  calendarLinks.forEach(link => link.setAttribute('href', language === 'en' ? 'wedding-en.ics' : 'wedding.ics'));
  document.querySelectorAll('[data-language]').forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.language === language));
  });
  document.querySelectorAll('[data-status-key]').forEach(element => {
    element.textContent = t(element.dataset.statusKey) + (element.dataset.statusSuffix || '');
  });
  refreshMenuLabel();
  if (userAction) {
    try { localStorage.setItem('invitation-language', language); } catch {}
    const url = new URL(location.href);
    url.searchParams.set('lang', language);
    try { history.replaceState(null, '', url); } catch {}
    requestAnimationFrame(() => {
      if (anchor) window.scrollBy({ top: anchor.getBoundingClientRect().top - anchorTop, behavior: 'instant' });
      document.dispatchEvent(new Event('invitation-language-change'));
    });
  }
}

